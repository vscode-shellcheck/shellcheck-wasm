// Feature probes for choosing an artifact: a module is valid only where the engine implements
// the instruction it contains. WebAssembly.validate is synchronous and cheap at this size.

/** `(func (type 0) return_call 0)` */
export const TAIL_CALL_PROBE = new Uint8Array([
  0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00, 0x01, 0x04, 0x01, 0x60, 0x00, 0x00, 0x03, 0x02,
  0x01, 0x00, 0x0a, 0x06, 0x01, 0x04, 0x00, 0x12, 0x00, 0x0b,
]);

/** `(func (type 0) v128.const i32x4 0 0 0 0 drop)` */
export const SIMD_PROBE = new Uint8Array([
  0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00, 0x01, 0x04, 0x01, 0x60, 0x00, 0x00, 0x03, 0x02,
  0x01, 0x00, 0x0a, 0x17, 0x01, 0x15, 0x00, 0xfd, 0x0c, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x1a, 0x0b,
]);

export function probe() {
  const validate = (bytes) => {
    try {
      return WebAssembly.validate(bytes);
    } catch {
      return false;
    }
  };
  return { tailCall: validate(TAIL_CALL_PROBE), simd: validate(SIMD_PROBE) };
}
