// Each probe is a minimal module that validates only where the engine implements the
// instruction in it.

/** `(func return_call 0)` */
const TAIL_CALL_PROBE = new Uint8Array([
  0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00, 0x01, 0x04, 0x01, 0x60, 0x00, 0x00, 0x03, 0x02,
  0x01, 0x00, 0x0a, 0x06, 0x01, 0x04, 0x00, 0x12, 0x00, 0x0b,
]);

/** `(func v128.const i32x4 0 0 0 0 drop)` */
const SIMD_PROBE = new Uint8Array([
  0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00, 0x01, 0x04, 0x01, 0x60, 0x00, 0x00, 0x03, 0x02,
  0x01, 0x00, 0x0a, 0x17, 0x01, 0x15, 0x00, 0xfd, 0x0c, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x1a, 0x0b,
]);

/**
 * Whether this engine can compile `shellcheck.wasm`, which needs wasm tail calls and SIMD:
 * false on Safari before 18.2 and Firefox ESR 115, where compiling it would throw a
 * `CompileError` a user cannot act on.
 */
export function isArtifactSupported(): boolean {
  return WebAssembly.validate(TAIL_CALL_PROBE) && WebAssembly.validate(SIMD_PROBE);
}
